import { canonicalJson, sha256 } from "../util.ts";
import type { EntryMaturity } from "./entry-maturity.ts";
import type { InvestmentHistory } from "./investments.ts";
import { identified } from "./investments.ts";
import { leadStatus } from "./leadership.ts";
import type { Rate } from "./ratio.ts";
import { rate } from "./ratio.ts";

export const BLACK_SHEEP = {
  sinceYear: 2020,
  minimumSample: 10,
  minimumPeers: 10,
  minimumEarlyStageShare: 0.5,
  weights: { leads: 0.5, independent_entry: 0.5 },
  resamples: 1000,
  interval: 0.9,
  seed: 1,
} as const;

/** One first investment, reduced to the two facts the score reads. */
export interface SheepObservation {
  /** The company already had a VC round dated before this one; null when partial dates prevent ordering. */
  late: boolean | null;
  /** True when flagged lead or the only disclosed investor; false when another participant is flagged lead. */
  led: boolean | null;
  soleInvestor: boolean;
}

export interface SheepProfile {
  investorId: string;
  name: string;
  /** Pre-seed and seed share of all first investments with a known stage, over the whole history. */
  earlyStageShare: number | null;
  observations: SheepObservation[];
}

/** Each peer's share for each component, sorted and unlabelled, generated by `npm run calibrate`. */
export interface Calibration {
  peer_set_version: string;
  algorithm_version: string;
  leads: number[];
  independent_entry: number[];
}

export interface BlackSheepScore {
  role: "score";
  question: "How often does this investor lead or go in first, rather than follow others, compared with early-stage peers?";
  scale: "0 follows the flock the most among peers, 100 is the most contrarian";
  status: "scored" | "not_scored";
  reasons: string[];
  value: number | null;
  range: { low: number; high: number; interval: number; resamples: number } | null;
  components: {
    leads: {
      score: number | null;
      follows_others: Rate;
      sole_investor: number;
      peers: number;
    };
    independent_entry: {
      score: number | null;
      late_entry: Rate;
      follows_others_when_late: Rate;
      late_follow_share: number | null;
      peers: number;
    };
  };
  calibration: {
    peer_set_version: string;
    algorithm_version: string;
    fingerprint: string;
  };
  parameters: typeof BLACK_SHEEP;
}

export function sheepProfile(history: InvestmentHistory, entry: EntryMaturity, name: string): SheepProfile {
  const d = entry.distribution;
  const observations = identified(history)
    .filter((company) => Number(company.initial!.announcedDate?.slice(0, 4)) >= BLACK_SHEEP.sinceYear)
    .map((company): SheepObservation => {
      const round = company.initial!;
      const status = leadStatus(round, history.investorId);
      const soleInvestor = round.participants.length === 1;
      const context = company.entry!;
      return {
        late: context.priorVcRounds > 0 ? true : context.uncertainVcRounds > 0 ? null : false,
        led: soleInvestor || status === "sole_lead" || status === "co_lead" ? true : status === "not_led" ? false : null,
        soleInvestor,
      };
    });
  return {
    investorId: history.investorId,
    name,
    earlyStageShare: entry.known_stage === 0 ? null : (d.pre_seed.count + d.seed.count) / entry.known_stage,
    observations,
  };
}

interface Behaviour {
  follow: Rate;
  late: Rate;
  followWhenLate: Rate;
  followShare: number | null;
  lateFollowShare: number | null;
}

const share = (r: Rate): number | null => (r.denominator === 0 ? null : r.numerator / r.denominator);

function behaviour(observations: SheepObservation[]): Behaviour {
  const usable = observations.filter((o) => o.led !== null);
  const ordered = observations.filter((o) => o.late !== null);
  const late = ordered.filter((o) => o.late);
  const lateUsable = late.filter((o) => o.led !== null);
  const follow = rate(usable.filter((o) => !o.led).length, usable.length);
  const lateRate = rate(late.length, ordered.length);
  const followWhenLate = rate(lateUsable.filter((o) => !o.led).length, lateUsable.length);
  const lateShare = share(lateRate);
  const followLateShare = share(followWhenLate);
  return {
    follow,
    late: lateRate,
    followWhenLate,
    followShare: share(follow),
    lateFollowShare: lateShare === null || followLateShare === null ? null : lateShare * followLateShare,
  };
}

const SHARE_DECIMALS = 1_000_000;
const roundShare = (value: number): number => Math.round(value * SHARE_DECIMALS) / SHARE_DECIMALS;

const isEarlyStage = (profile: SheepProfile) =>
  profile.earlyStageShare !== null && profile.earlyStageShare >= BLACK_SHEEP.minimumEarlyStageShare;

/** Builds the peer distributions from stored peers, keeping only peers with enough early-stage data for each component. */
export function calibrate(peers: SheepProfile[], peerSetVersion: string, algorithmVersion: string): Calibration {
  const points = (pick: (b: Behaviour) => number | null, minimum: (b: Behaviour) => boolean) =>
    peers
      .filter(isEarlyStage)
      .map((peer) => behaviour(peer.observations))
      .filter(minimum)
      .map((b) => roundShare(pick(b)!))
      .sort((a, b) => a - b);
  const enoughLeads = (b: Behaviour) => b.follow.denominator >= BLACK_SHEEP.minimumSample;
  return {
    peer_set_version: peerSetVersion,
    algorithm_version: algorithmVersion,
    leads: points((b) => b.followShare, enoughLeads),
    independent_entry: points((b) => b.lateFollowShare, (b) => enoughLeads(b) && b.followWhenLate.denominator >= BLACK_SHEEP.minimumSample),
  };
}

/** Drops one share equal to the investor's own, so a peer is not ranked against itself. */
function withoutSelf(shares: number[], own: number | null): number[] {
  const index = own === null ? -1 : shares.indexOf(roundShare(own));
  return index === -1 ? shares : [...shares.slice(0, index), ...shares.slice(index + 1)];
}

/** Share of peers below `value`, ties counted half, so 100 means above every peer. */
const percentile = (value: number, peers: number[]): number =>
  (100 * (peers.filter((p) => p < value).length + peers.filter((p) => p === value).length / 2)) / peers.length;

function mulberry32(seed: number): () => number {
  let state = seed;
  return () => {
    state = (state + 0x6d2b79f5) | 0;
    let t = Math.imul(state ^ (state >>> 15), 1 | state);
    t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t;
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}

const quantile = (sorted: number[], q: number): number => sorted[Math.floor(q * (sorted.length - 1))]!;

/**
 * Ranks one investor against the calibrated early-stage peers on two behaviours: how rarely it follows another
 * lead, and how rarely it joins an already funded company behind someone else's lead. Each is a
 * percentile among peers, inverted so that higher is more contrarian, and the score averages them.
 */
export function blackSheepScore(target: SheepProfile, calibration: Calibration): BlackSheepScore {
  const p = BLACK_SHEEP;
  const own = behaviour(target.observations);
  const followPeers = withoutSelf(calibration.leads, own.followShare);
  const latePeers = withoutSelf(calibration.independent_entry, own.lateFollowShare);

  const reasons: string[] = [];
  if (!isEarlyStage(target)) {
    reasons.push("Most first investments with a known stage are after seed, so the early-stage peer set does not apply.");
  }
  if (own.follow.denominator < p.minimumSample) {
    reasons.push(`Only ${own.follow.denominator} first investments since ${p.sinceYear} have a usable lead status (minimum ${p.minimumSample}).`);
  }
  if (own.followWhenLate.denominator < p.minimumSample) {
    reasons.push(
      `Only ${own.followWhenLate.denominator} first investments since ${p.sinceYear} joined an already funded company with a usable lead status (minimum ${p.minimumSample}).`,
    );
  }
  if (followPeers.length < p.minimumPeers || latePeers.length < p.minimumPeers) {
    reasons.push(`The calibration has too few peers (minimum ${p.minimumPeers}).`);
  }

  const scoreOf = (b: Behaviour) => {
    const leads = 100 - percentile(roundShare(b.followShare!), followPeers);
    const independent = 100 - percentile(roundShare(b.lateFollowShare!), latePeers);
    return { leads, independent, value: p.weights.leads * leads + p.weights.independent_entry * independent };
  };

  let scored: ReturnType<typeof scoreOf> | null = null;
  let range: BlackSheepScore["range"] = null;
  if (reasons.length === 0) {
    scored = scoreOf(own);
    const random = mulberry32(p.seed);
    const n = target.observations.length;
    const values: number[] = [];
    for (let i = 0; i < p.resamples; i++) {
      const sample = Array.from({ length: n }, () => target.observations[Math.floor(random() * n)]!);
      const b = behaviour(sample);
      if (b.followShare !== null && b.lateFollowShare !== null) values.push(scoreOf(b).value);
    }
    values.sort((a, b) => a - b);
    const tail = (1 - p.interval) / 2;
    range = { low: Math.round(quantile(values, tail)), high: Math.round(quantile(values, 1 - tail)), interval: p.interval, resamples: values.length };
  }

  return {
    role: "score",
    question: "How often does this investor lead or go in first, rather than follow others, compared with early-stage peers?",
    scale: "0 follows the flock the most among peers, 100 is the most contrarian",
    status: scored ? "scored" : "not_scored",
    reasons,
    value: scored && Math.round(scored.value),
    range,
    components: {
      leads: {
        score: scored && Math.round(scored.leads),
        follows_others: own.follow,
        sole_investor: target.observations.filter((o) => o.soleInvestor).length,
        peers: followPeers.length,
      },
      independent_entry: {
        score: scored && Math.round(scored.independent),
        late_entry: own.late,
        follows_others_when_late: own.followWhenLate,
        late_follow_share: own.lateFollowShare === null ? null : Math.round(own.lateFollowShare * 10_000) / 10_000,
        peers: latePeers.length,
      },
    },
    calibration: {
      peer_set_version: calibration.peer_set_version,
      algorithm_version: calibration.algorithm_version,
      fingerprint: `sha256:${sha256(canonicalJson(calibration))}`,
    },
    parameters: BLACK_SHEEP,
  };
}
