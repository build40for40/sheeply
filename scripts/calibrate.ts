import { writeFileSync } from "node:fs";
import { parseArgs } from "node:util";
import { blackSheepScore, calibrate } from "../src/analysis/black-sheep.ts";
import { latestCompleteRun } from "../src/analysis/dataset.ts";
import { openWorkingDatabase } from "../src/cli/analyse-command.ts";
import { DEFAULT_DB_PATH, loadDealroomConfig, loadDotEnv } from "../src/config.ts";
import { DealroomApiError, DealroomClient } from "../src/dealroom/client.ts";
import { ingestInvestor } from "../src/ingest/fetch.ts";
import { ALGORITHM_VERSION } from "../src/version.ts";
import { PEER_SET, loadSheepProfile } from "./peers.ts";

const OUTPUT = new URL("../src/analysis/black-sheep-calibration.ts", import.meta.url);

const { values } = parseArgs({
  options: { db: { type: "string" }, refresh: { type: "boolean", default: false } },
});
loadDotEnv();
const log = (message: string) => process.stderr.write(`${message}\n`);
const db = openWorkingDatabase(values.db ?? process.env.SHEEPLY_DB ?? DEFAULT_DB_PATH, log);

let client: DealroomClient | undefined;
for (const [index, peer] of PEER_SET.investors.entries()) {
  if (latestCompleteRun(db, peer.id) !== null && !values.refresh) continue;
  log(`[${index + 1}/${PEER_SET.investors.length}] Fetching ${peer.name}`);
  client ??= new DealroomClient(loadDealroomConfig(), { log });
  try {
    await ingestInvestor(db, client, peer.id, { log });
  } catch (error) {
    if (!(error instanceof DealroomApiError)) throw error;
    log(`Skipping ${peer.name}: ${error.message}`);
  }
}
if (client) log(`Fetched with ${client.usage.requests} requests, ${client.usage.credits} Dealroom credits`);

const profiles = PEER_SET.investors.filter((peer) => latestCompleteRun(db, peer.id) !== null).map((peer) => loadSheepProfile(db, peer.id));
db.close();
const calibration = calibrate(profiles, PEER_SET.version, ALGORITHM_VERSION);

writeFileSync(
  OUTPUT,
  `import type { Calibration } from "./black-sheep.ts";

/** Generated by \`npm run calibrate\` from the peer set in scripts/peers.ts. Shares only, sorted, with no peer names or ids. */
export const CALIBRATION: Calibration = {
  peer_set_version: ${JSON.stringify(calibration.peer_set_version)},
  algorithm_version: ${JSON.stringify(calibration.algorithm_version)},
  leads: ${JSON.stringify(calibration.leads)},
  independent_entry: ${JSON.stringify(calibration.independent_entry)},
};
`,
);
log(`Wrote ${OUTPUT.pathname}: ${calibration.leads.length} peers for leads, ${calibration.independent_entry.length} for independent entry`);

const ranking = profiles
  .map((profile) => ({ profile, score: blackSheepScore(profile, calibration) }))
  .sort((a, b) => (b.score.value ?? -1) - (a.score.value ?? -1) || (a.profile.name < b.profile.name ? -1 : 1));
for (const { profile, score } of ranking) {
  const range = score.range ? ` [${score.range.low}-${score.range.high}]` : "";
  log(`${String(score.value ?? "-").padStart(3)}${range.padEnd(10)} ${profile.name}${score.reasons.length ? `: ${score.reasons.join(" ")}` : ""}`);
}
